import { useState, useEffect } from 'react';
import { Bell, CheckCheck } from 'lucide-react';
import { notificationsApi } from '../services/api';
import { LoadingSpinner, ErrorMessage, EmptyState } from '../components/ui/index';
import { useToast } from '../context/ToastContext';

const EVENT_ICONS = {
  'task-created': { icon: '✅', color: '#34d399' },
  'task-updated': { icon: '✏️', color: '#fbbf24' },
  'task-completed': { icon: '🎉', color: '#a78bfa' },
  'task-deleted': { icon: '🗑️', color: '#ef4444' },
  'ai-suggestion': { icon: '✨', color: '#22d3ee' },
};

const NotificationsPage = () => {
  const toast = useToast();
  const [notifications, setNotifications] = useState([]);
  const [unreadCount, setUnreadCount] = useState(0);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const fetchNotifications = async () => {
    setLoading(true); setError(null);
    try {
      const { data } = await notificationsApi.getAll({ limit: 50 });
      setNotifications(data.data?.notifications || []);
      setUnreadCount(data.data?.unreadCount || 0);
    } catch (err) {
      setError(err.response?.data?.error || 'Failed to load notifications');
    } finally { setLoading(false); }
  };

  useEffect(() => { fetchNotifications(); }, []);

  const markAllRead = async () => {
    try {
      await notificationsApi.markRead([]);
      setNotifications((n) => n.map((item) => ({ ...item, read: true })));
      setUnreadCount(0);
      toast.success('All notifications marked as read');
    } catch { toast.error('Failed to mark as read'); }
  };

  const formatTime = (date) => {
    const d = new Date(date);
    const now = new Date();
    const diffMs = now - d;
    const diffMin = Math.floor(diffMs / 60000);
    if (diffMin < 1) return 'Just now';
    if (diffMin < 60) return `${diffMin}m ago`;
    const diffHr = Math.floor(diffMin / 60);
    if (diffHr < 24) return `${diffHr}h ago`;
    return d.toLocaleDateString();
  };

  return (
    <div className="animate-fade-in">
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: '1.5rem', flexWrap: 'wrap', gap: '1rem' }}>
        <div>
          <h1 style={{ fontSize: '1.75rem', fontWeight: 800, color: '#e2e2f0', margin: 0, display: 'flex', alignItems: 'center', gap: '0.75rem' }}>
            Notifications
            {unreadCount > 0 && (
              <span style={{ background: '#8b5cf6', color: 'white', borderRadius: 12, padding: '2px 9px', fontSize: '0.8rem', fontWeight: 600 }}>{unreadCount}</span>
            )}
          </h1>
          <p style={{ color: '#6b6b8a', fontSize: '0.875rem', marginTop: '0.25rem' }}>
            Task events processed by Node.js EventEmitter — asynchronously after API responses
          </p>
        </div>
        {unreadCount > 0 && (
          <button className="btn-outline" onClick={markAllRead} style={{ fontSize: '0.8rem' }}>
            <CheckCheck size={15} /> Mark all read
          </button>
        )}
      </div>

      {/* EventEmitter explanation */}
      <div className="glass-card" style={{ padding: '1rem 1.25rem', marginBottom: '1.5rem', borderColor: 'rgba(34,211,238,0.15)' }}>
        <p style={{ fontSize: '0.8125rem', color: '#6b6b8a', margin: 0, lineHeight: 1.6 }}>
          <span style={{ color: '#22d3ee', fontWeight: 600 }}>⚡ Event-Driven Architecture:</span> These notifications are generated by a Node.js <code style={{ background: 'rgba(139,92,246,0.1)', padding: '1px 5px', borderRadius: 4, color: '#a78bfa', fontSize: '0.8rem' }}>EventEmitter</code> that fires <em>after</em> the API response is sent. The HTTP response time and listener execution time are recorded separately in server logs, demonstrating non-blocking async processing.
        </p>
      </div>

      {loading && <LoadingSpinner message="Loading notifications..." />}
      {error && <ErrorMessage message={error} onRetry={fetchNotifications} />}
      {!loading && !error && notifications.length === 0 && (
        <EmptyState icon={Bell} title="No notifications yet" message="Notifications appear here when you create, update, or complete tasks. Each notification is generated asynchronously by Node.js EventEmitter after the API response." />
      )}

      <div style={{ display: 'flex', flexDirection: 'column', gap: '0.625rem' }}>
        {notifications.map((n) => {
          const cfg = EVENT_ICONS[n.eventType] || { icon: '🔔', color: '#8b5cf6' };
          return (
            <div
              key={n._id}
              className="glass-card"
              style={{ padding: '1rem 1.25rem', borderLeft: n.read ? undefined : `3px solid ${cfg.color}`, opacity: n.read ? 0.65 : 1 }}
            >
              <div style={{ display: 'flex', alignItems: 'flex-start', gap: '0.875rem' }}>
                <span style={{ fontSize: '1.25rem', flexShrink: 0 }}>{cfg.icon}</span>
                <div style={{ flex: 1, minWidth: 0 }}>
                  <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', flexWrap: 'wrap', gap: '0.25rem' }}>
                    <span style={{ fontSize: '0.875rem', fontWeight: n.read ? 400 : 600, color: '#e2e2f0' }}>{n.message}</span>
                    <span style={{ fontSize: '0.7rem', color: '#52526e', flexShrink: 0 }}>{formatTime(n.createdAt)}</span>
                  </div>
                  <div style={{ display: 'flex', gap: '0.875rem', marginTop: '0.375rem', flexWrap: 'wrap' }}>
                    <span style={{ fontSize: '0.72rem', color: '#52526e', background: 'rgba(82,82,110,0.15)', padding: '1px 7px', borderRadius: 4 }}>
                      {n.eventType}
                    </span>
                    {n.metadata?.apiResponseTime && (
                      <span style={{ fontSize: '0.72rem', color: '#52526e' }}>
                        API: {new Date(n.metadata.apiResponseTime).toLocaleTimeString()}
                      </span>
                    )}
                    {n.metadata?.listenerExecutionTime && (
                      <span style={{ fontSize: '0.72rem', color: '#22d3ee' }}>
                        Listener: {new Date(n.metadata.listenerExecutionTime).toLocaleTimeString()} (+{n.metadata.timingDifferenceMs}ms)
                      </span>
                    )}
                    {!n.read && (
                      <span style={{ fontSize: '0.7rem', color: cfg.color, fontWeight: 600 }}>• New</span>
                    )}
                  </div>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};

export default NotificationsPage;
